export const INTERLUDES: InterludeShot[] = PICKS.map((p) => {
  if ('product' in p) {
    const product = getProduct(p.product);
    if (!product) throw new Error(`interlude: no product "${p.product}"`);
    return {
      src: p.src,
      position: p.position,
      href: `/products/${product.slug}`,
      caption: product.name,
      alt: product.short,
    };
  }
  return {
    src: p.src,
    position: p.position,
    href: `/categories/${p.category}`,
    caption: CATEGORIES[p.category].title,
    alt: p.alt,
  };
});
